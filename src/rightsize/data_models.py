"""Schemas for everything under data/ (lightweight rule 2).

Numbers live in data files so they can change without a code release, which also means
nothing checks them unless something here does. Each file shape has a Pydantic model; the
tests validate every data file against its model, fail on any file no model covers, and
check that the JSON Schemas in data/schema/ are the ones these models export - so a third
party correcting a bandwidth can validate their edit without reading this code.

Nothing here runs when rightsize is imported or used: load_yaml stays a plain read, and
validation is a test and CI concern.

    python -c "from rightsize.data_models import validate_all; print(validate_all())"
"""

from __future__ import annotations

import datetime as _dt
import fnmatch
import re
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator, model_validator

Vendor = Literal["nvidia", "amd", "intel", "apple", "qualcomm", "cpu", "other"]


class _Strict(BaseModel):
    # a misspelt key is a silent no-op in YAML; refuse it instead
    model_config = ConfigDict(extra="forbid")


class Source(_Strict):
    """Where a number came from. Required on every record (lightweight rule 2)."""

    source_url: str
    fetched_at: str
    hand: bool = False
    note: str | None = None

    @field_validator("source_url")
    @classmethod
    def _https(cls, v: str) -> str:
        if not v.startswith("https://"):
            raise ValueError("source_url must be an https:// link someone can open")
        return v

    @field_validator("fetched_at")
    @classmethod
    def _iso_date(cls, v: str) -> str:
        _dt.date.fromisoformat(str(v))
        return str(v)


