class VariantsFile(_Strict):
    """data/models/variants.yaml: how quantized copies of a model are published on the Hub."""

    provenance: Source
    strip_patterns: list[str] = Field(min_length=1)
    formats: list[VariantFormat] = Field(min_length=1)
    publishers: list[QuantPublisher] = Field(default_factory=list)

    @model_validator(mode="after")
    def _consistent(self) -> VariantsFile:
        for pattern in self.strip_patterns:
            re.compile(pattern)
        ids = [f.id for f in self.formats]
        dupes = sorted({i for i in ids if ids.count(i) > 1})
        if dupes:
            raise ValueError(f"format id used twice: {dupes}")
        unknown = sorted({f for p in self.publishers for f in p.formats} - set(ids))
        if unknown:
            raise ValueError(f"publishers name formats the table does not have: {unknown}")
        return self


