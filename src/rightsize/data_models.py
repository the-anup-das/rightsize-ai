class _Sliding(_Strict):
    pattern: int = Field(ge=1)
    window_key: str | None = None
    window_default: int | None = Field(default=None, gt=0)


class _Hybrid(_Strict):
    rule: Literal[
        "full_attention_interval", "attn_layer_period", "hybrid_override_pattern",
        "layer_types", "parallel",
    ]
    interval_default: int | None = None


class KvRule(_Strict):
    model_types: list[str] = Field(min_length=1)
    sliding: _Sliding | None = None
    mla: bool = False
    hybrid: _Hybrid | None = None
    note: str | None = None
    source_url: str

    @model_validator(mode="after")
    def _one_layout(self) -> KvRule:
        if sum([self.sliding is not None, self.mla, self.hybrid is not None]) != 1:
            raise ValueError("a rule sets exactly one of sliding, mla or hybrid")
        return self


class _KvDefaults(_Strict):
    n_ubatch: int = Field(gt=0)
    swa_pad: int = Field(gt=0)
    recurrent_state_bytes: int = Field(gt=0)
    swa_source_url: str


class KvCacheFile(_Strict):
    """data/runtimes/<runtime>/kv_cache.yaml: how a runtime lays out the KV cache (F3)."""

    runtime: str
    version: str
    source_url: str
    fetched_at: str
    defaults: _KvDefaults
    architectures: list[KvRule]

    @field_validator("architectures")
    @classmethod
    def _no_overlap(cls, v: list[KvRule]) -> list[KvRule]:
        seen: set[str] = set()
        for rule in v:
            clash = seen.intersection(rule.model_types)
            if clash:
                raise ValueError(f"model types claimed by two rules: {sorted(clash)}")
            seen.update(rule.model_types)
        return v


# ---------------------------------------------------------------- registry


def _recipe_model() -> type[BaseModel]:
    from rightsize.registry.schema import Recipe

    return Recipe


#: data/ path pattern -> (schema file name, model). Every YAML file under data/ must match
#: one of these; tests fail on a file nothing covers.
DATA_FILES: dict[str, tuple[str, Any]] = {
    "quants/gguf_bpw.yaml": ("gguf_bpw", GgufBpwFile),
    "hardware/presets.yaml": ("presets", PresetsFile),
    "hardware/gpus.yaml": ("gpu_catalog", GpuCatalogFile),
    "hardware/bandwidth*.yaml": ("bandwidth", BandwidthFile),
    "quality/gate_thresholds.yaml": ("gate_thresholds", GateThresholdsFile),
    "quality/gguf_types.yaml": ("gguf_types", GgufTypesFile),
    "finetune/unsloth_vram.yaml": ("finetune_floors", FinetuneFloorsFile),
    "models/candidates.yaml": ("candidates", CandidatesFile),
    "rules/*.yaml": ("rules", RulesFile),
    "runtimes/*/kv_cache.yaml": ("kv_cache", KvCacheFile),
    "recipes/*/*.yaml": ("recipe", _recipe_model),
}


def model_for(relative: str) -> tuple[str, type[BaseModel]] | None:
    for pattern, (name, model) in DATA_FILES.items():
        if fnmatch.fnmatch(relative, pattern):
            return name, (model() if model is _recipe_model else model)
    return None


def validate_all(root: str | Path | None = None) -> list[str]:
    """Every problem across data/, as readable lines. Empty means clean."""
    import yaml

    from rightsize._data import data_dir

    base = Path(root) if root else data_dir()
    problems: list[str] = []
    for path in sorted(base.rglob("*.yaml")):
        rel = path.relative_to(base).as_posix()
        found = model_for(rel)
        if found is None:
            problems.append(f"{rel}: no schema covers this file (add it to DATA_FILES)")
            continue
        _, model = found
        try:
            model.model_validate(yaml.safe_load(path.read_text(encoding="utf-8")))
        except ValidationError as exc:
            for err in exc.errors()[:5]:
                where = ".".join(str(p) for p in err["loc"])
                problems.append(f"{rel}: {where}: {err['msg']}")
    return problems


def json_schemas() -> dict[str, dict[str, Any]]:
    """Schema name -> JSON Schema, as written to data/schema/ by scripts/export_schemas.py."""
    out: dict[str, dict[str, Any]] = {}
    for name, model in DATA_FILES.values():
        m = model() if model is _recipe_model else model
        out[name] = m.model_json_schema()
    return out
