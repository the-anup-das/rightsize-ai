class GateThresholdsFile(_Strict):
    """data/quality/gate_thresholds.yaml: the quantization quality gate (F8)."""

    provenance: Source
    kld: _KldBand
    top1_agreement: _AgreementBand

    @model_validator(mode="after")
    def _ordered(self) -> GateThresholdsFile:
        if not self.kld.pass_below < self.kld.warn_below:
            raise ValueError("kld: pass_below must be below warn_below")
        if not self.top1_agreement.pass_above > self.top1_agreement.warn_above:
            raise ValueError("top1_agreement: pass_above must be above warn_above")
        return self


