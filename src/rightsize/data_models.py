class GgufBpwFile(_Strict):
    """data/quants/gguf_bpw.yaml: real bits per weight, scales and mins included."""

    provenance: Source
    tensor_types: dict[str, float]
    file_types_provenance: Source
    file_types: dict[str, float]

    @field_validator("tensor_types", "file_types")
    @classmethod
    def _plausible_bpw(cls, v: dict[str, float]) -> dict[str, float]:
        bad = {k: x for k, x in v.items() if not 1.0 <= x <= 32.0}
        if bad:
            raise ValueError(f"bits per weight outside 1-32: {bad}")
        return v


