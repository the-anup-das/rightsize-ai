class GgmlTypesFile(_Strict):
    """data/quants/ggml_types.yaml: the numbers a GGUF header uses for tensor and file types,
    generated by scripts/ingest_ggml_types.py."""

    provenance: Source
    llama_cpp: str
    tensor_types: list[GgmlTensorType] = Field(min_length=1)
    file_types: list[GgufFileType] = Field(min_length=1)

    @model_validator(mode="after")
    def _unique(self) -> GgmlTypesFile:
        for label, rows in (("tensor", self.tensor_types), ("file", self.file_types)):
            for attr in ("id", "name"):
                values = [getattr(r, attr) for r in rows]
                dupes = sorted({str(x) for x in values if values.count(x) > 1})
                if dupes:
                    raise ValueError(f"{label} type {attr} used twice: {dupes}")
        return self


